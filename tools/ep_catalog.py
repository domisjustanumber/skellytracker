#!/usr/bin/env python3
"""Check the EP catalog of ``skellytracker/core/eps/``, and write its lock.

Usage::

    uv run python tools/ep_catalog.py --check
    uv run python tools/ep_catalog.py --refresh [--cache DIR]

``--check`` uses no network. It fails when:

- ``ort_core.version`` of ``ep_catalog.yaml`` is not the ``onnxruntime`` pin of ``pyproject.toml`` and
  of ``uv.lock``;
- ``catalog_revision`` of ``ep_lock.yaml`` is not the revision of ``ep_catalog.yaml``: run
  ``--refresh`` after each change of the catalog;
- a pack has no exact version, or the lock has no row for the pack on a platform of the catalog;
- a wheel of the lock has no ``https`` URL, no sha256 of 64 hex characters or no sizes, or a lock row
  has no library path;
- two packs with one ``ep_name`` have different ``exclusive_group`` values, or a pack has none;
- a platform of the catalog is a macOS platform: macOS has no pack;
- a reserved EP key has a user pack row (``packs``), or an EP key that is not reserved has no
  ``options.allowed`` map;
- an allow-list holds ``device_id``, or an allowed value is not a list of strings or ``positive-int``;
- a hardware class has no ``id``, no ``ranking_evidence`` or a candidate that is not an EP key that a
  request can name, or two hardware classes have one ``id``;
- a successor of a key of ``legacy_keys`` is not an EP key that a request can name.

``--refresh`` uses the network. Only this mode writes ``ep_lock.yaml``. For each pack and each
platform of the catalog, it reads the PEP 503 page of each wheel, downloads the wheel to the cache
folder (default: a temporary folder), and writes the URL, the sha256 and the sizes to the lock. It
refuses a URL that is not ``https`` and a file whose sha256 is not the sha256 of the index page.
It also writes the path of the EP library in the pack, the folders of the Windows DLLs of the
dependency wheels, and the Linux libraries to preload. The Linux preload list is not verified.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import tempfile
import urllib.parse
import urllib.request
import zipfile
from collections.abc import Callable
from html.parser import HTMLParser
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
EPS = REPO_ROOT / "skellytracker" / "core" / "eps"
PLATFORM_PATTERNS = {"win_amd64": r"win_amd64", "manylinux_x86_64": r"manylinux_\d+_\d+_x86_64"}
LOCK_HEADER = "# Written by `tools/ep_catalog.py --refresh`. Do not edit this file by hand.\n"


class Anchors(HTMLParser):
    """The `(href, text)` of each anchor of a PEP 503 page. An attribute value can hold `>`."""

    def __init__(self, page: str) -> None:
        super().__init__()
        self.found: list[tuple[str, str]] = []
        self._href: str | None = None
        self.feed(page)

    def handle_starttag(self, tag, attrs):
        if tag == "a":
            self._href = dict(attrs).get("href")

    def handle_data(self, data):
        if self._href and data.strip():
            self.found.append((self._href, data.strip()))
            self._href = None


def revision_of(catalog_text: str) -> str:
    return hashlib.sha256(catalog_text.replace("\r\n", "\n").encode("utf-8")).hexdigest()


def pack_rows(catalog: dict) -> list[tuple[str, dict]]:
    """Each pack row with its EP key: the user packs and the test packs."""
    return [(key, pack) for key, row in catalog["eps"].items() for pack in [*row.get("packs", ()), *row.get("test_packs", ())]]


def pack_wheels(pack: dict, platform: str) -> list[tuple[str, str, str]]:
    """`(package, version, index)` of the plugin wheel and of each dependency wheel of a pack."""
    wheels = [(pack["package"], pack["version"], pack["index"])]
    for wheel in pack.get("dependency_wheels", ()):
        version = wheel["version"]
        wheels.append((wheel["package"], version[platform] if isinstance(version, dict) else version, wheel["index"]))
    return wheels


def check(catalog: dict, lock: dict, catalog_text: str, pyproject_text: str, uv_lock_text: str) -> list[str]:
    """The problems of the catalog and its lock. An empty list is a pass."""
    problems: list[str] = []
    version = catalog["ort_core"]["version"]
    if f'"onnxruntime=={version}"' not in pyproject_text:
        problems.append(f"ort_core.version {version} is not the onnxruntime pin of pyproject.toml")
    if not re.search(rf'name = "onnxruntime"\r?\nversion = "{re.escape(version)}"', uv_lock_text):
        problems.append(f"ort_core.version {version} is not the onnxruntime version of uv.lock")
    if lock.get("catalog_revision") != revision_of(catalog_text):
        problems.append("ep_lock.yaml is not made from this ep_catalog.yaml: run tools/ep_catalog.py --refresh")
    platforms = catalog.get("platforms", [])
    problems += [f"platform {name}: macOS has no pack" for name in platforms if "mac" in name or "darwin" in name]
    groups: dict[str, str] = {}
    for key, row in catalog["eps"].items():
        if row["kind"] == "reserved" and row.get("packs"):
            problems.append(f"{key}: a reserved key has a user pack row")
        if row["kind"] == "reserved":
            continue
        allowed = row.get("options", {}).get("allowed")
        if not isinstance(allowed, dict):
            problems.append(f"{key}: no options.allowed map")
            continue
        for name, rule in allowed.items():
            if name == "device_id":
                problems.append(f"{key}: device_id is not an allowed option")
            if rule != "positive-int" and not (isinstance(rule, list) and all(isinstance(v, str) for v in rule)):
                problems.append(f"{key}: the values of {name} are not a list of strings or positive-int")
    for key, pack in pack_rows(catalog):
        name = f"{key}/{pack.get('id')}"
        if not re.fullmatch(r"\d+(\.\d+)+", str(pack.get("version", ""))):
            problems.append(f"{name}: no exact version")
        group = pack.get("exclusive_group")
        if not group or groups.setdefault(pack["ep_name"], group) != group:
            problems.append(f"{name}: no exclusive_group, or a group that differs for the EP name {pack['ep_name']}")
        for platform in platforms:
            row = lock.get("packs", {}).get(pack["id"], {}).get(platform)
            if row is None:
                problems.append(f"{name}: the lock has no row for {platform}")
                continue
            if not row.get("library"):
                problems.append(f"{name} {platform}: the lock has no library path")
            for wheel in row.get("wheels", ()):
                if not str(wheel.get("url", "")).startswith("https://"):
                    problems.append(f"{name} {platform}: the URL of {wheel.get('filename')} is not https")
                if not re.fullmatch(r"[0-9a-f]{64}", str(wheel.get("sha256", ""))):
                    problems.append(f"{name} {platform}: {wheel.get('filename')} has no sha256")
                if not (isinstance(wheel.get("download_bytes"), int) and isinstance(wheel.get("unpacked_bytes"), int)):
                    problems.append(f"{name} {platform}: {wheel.get('filename')} has no sizes")
            if len(row.get("wheels", ())) != len(pack_wheels(pack, platform)):
                problems.append(f"{name} {platform}: the lock does not hold each wheel of the pack")
    usable = {key for key, row in catalog["eps"].items() if row["kind"] != "reserved"}
    ids: set[str] = set()
    for row in catalog.get("hardware_classes", ()):
        row_id = row.get("id")
        if not row_id or row_id in ids:
            problems.append(f"hardware class {row_id}: no id, or an id that is used two times")
        ids.add(row_id)
        if not row.get("ranking_evidence"):
            problems.append(f"hardware class {row_id}: no ranking_evidence")
        problems += [f"hardware class {row_id}: the candidate {c} is not an EP key" for c in row.get("candidates", ()) if c not in usable]
    for old, successors in catalog.get("legacy_keys", {}).items():
        problems += [f"legacy key {old}: the successor {s} is not an EP key" for s in successors if s not in usable]
    return problems


def http_get(url: str) -> bytes:
    if not url.startswith("https://"):
        raise ValueError(f"not an https URL: {url}")
    with urllib.request.urlopen(url, timeout=120) as response:  # noqa: S310 - https only, checked above
        return response.read()


def find_wheel(page: str, page_url: str, package: str, version: str, platform: str) -> tuple[str, str, str | None]:
    """`(filename, URL, sha256 of the page or None)` of the wheel of a version and a platform on a PEP 503 page."""
    wanted = re.compile(rf"{re.escape(package.replace('-', '_'))}-{re.escape(version)}-[^-]+-[^-]+-{PLATFORM_PATTERNS[platform]}\.whl", re.IGNORECASE)
    for href, text in Anchors(page).found:
        if wanted.fullmatch(text):
            url, _, fragment = urllib.parse.urljoin(page_url, href).partition("#")
            if not url.startswith("https://"):
                raise ValueError(f"{text}: the URL is not https")
            return text, url, fragment.removeprefix("sha256=") if fragment.startswith("sha256=") else None
    raise LookupError(f"{package}=={version} has no wheel for {platform} on {page_url}")


def lock_row(pack: dict, platform: str, indexes: dict, cache: Path, get: Callable[[str], bytes]) -> dict:
    wheels, members, dependency_members = [], [], []
    for position, (package, version, index) in enumerate(pack_wheels(pack, platform)):
        page_url = indexes[index] + re.sub(r"[-_.]+", "-", package).lower() + "/"
        filename, url, page_sha = find_wheel(get(page_url).decode("utf-8", "replace"), page_url, package, version, platform)
        path = cache / filename
        if not path.exists():
            path.write_bytes(get(url))
        sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
        if page_sha is not None and page_sha != sha256:
            path.unlink()
            raise ValueError(f"{filename}: the sha256 of the file is not the sha256 of the index page")
        with zipfile.ZipFile(path) as archive:
            infos = [info for info in archive.infolist() if not info.is_dir()]
        names = [info.filename for info in infos]
        members += names
        dependency_members += names if position else []
        wheels.append({"package": package, "version": version, "filename": filename, "url": url, "sha256": sha256,
                       "index_hash": "sha256" if page_sha else "none", "download_bytes": path.stat().st_size,
                       "unpacked_bytes": sum(info.file_size for info in infos)})
    library_name = pack["library"][platform]
    library = next((name for name in members if name.rsplit("/", 1)[-1] == library_name), None)
    if library is None:
        raise LookupError(f"{pack['id']} {platform}: no wheel holds {library_name}")
    row = {"library": library, "download_bytes": sum(w["download_bytes"] for w in wheels),
           "unpacked_bytes": sum(w["unpacked_bytes"] for w in wheels), "wheels": wheels}
    if platform.startswith("win"):
        row["path_dirs"] = sorted({name.rsplit("/", 1)[0] for name in dependency_members if name.lower().endswith(".dll")})
    else:
        libraries = [name for name in dependency_members if re.search(r"\.so(\.\d+)*$", name) and "nvblas" not in name]
        row["preload"] = sorted(libraries, key=lambda name: (0 if "cublasLt" in name else 1 if "cublas" in name else 2, name))
    return row


def refresh(catalog: dict, catalog_text: str, cache: Path, get: Callable[[str], bytes] = http_get) -> dict:
    """The lock of `catalog`: one row for each pack and each platform."""
    packs = {pack["id"]: {platform: lock_row(pack, platform, catalog["indexes"], cache, get) for platform in catalog["platforms"]}
             for _, pack in pack_rows(catalog)}
    return {"catalog_revision": revision_of(catalog_text), "packs": packs}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--refresh", action="store_true")
    parser.add_argument("--cache", type=Path, help="the folder for the downloaded wheels of --refresh")
    args = parser.parse_args(argv)
    catalog_text = (EPS / "ep_catalog.yaml").read_text(encoding="utf-8")
    catalog = yaml.safe_load(catalog_text)
    if args.refresh:
        with tempfile.TemporaryDirectory() as temporary:
            cache = args.cache or Path(temporary)
            cache.mkdir(parents=True, exist_ok=True)
            lock = refresh(catalog, catalog_text, cache)
        (EPS / "ep_lock.yaml").write_text(LOCK_HEADER + yaml.safe_dump(lock, sort_keys=False), encoding="utf-8", newline="\n")
        print("ep_lock.yaml: written")
        return 0
    lock = yaml.safe_load((EPS / "ep_lock.yaml").read_text(encoding="utf-8")) or {}
    problems = check(catalog, lock, catalog_text, (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"),
                     (REPO_ROOT / "uv.lock").read_text(encoding="utf-8"))
    for problem in problems:
        print(problem)
    print("EP catalog: pass" if not problems else f"EP catalog: {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())

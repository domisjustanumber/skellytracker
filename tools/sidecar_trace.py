def load_inventory(repo_root: Path = REPO_ROOT) -> dict[str, Any]:
    """Load `specs/model-sidecar/inventory.yaml`.

    It always has an `examples`, a `no_model` and a `proposed` entry.
    """
    data = yaml.safe_load(
        (spec_dir(repo_root) / "inventory.yaml").read_text(encoding="utf-8")
    )
    data = data or {}
    data.setdefault("examples", {})
    data["no_model"] = data.get("no_model") or {}
    data.setdefault("proposed", [])
    return data


@dataclass(frozen=True)
class Sidecar:
    """A sidecar that the scan found, resolved and normalized."""

    key: str
    model_id: str
    source: str
    origin: str  # "package" or "example"
    path: str  # relative to the repository root, with forward slashes
    schema_version: str
    resolved: dict[str, Any] = field(repr=False)
    normalized: dict[str, Any] = field(repr=False)
    derived: tuple[str, ...]

    @property
    def legacy(self) -> bool:
        """True when the sidecar is older than `vNEXT`, which is newer than every dated version."""
        return self.schema_version != "vNEXT"


@dataclass(frozen=True)
class Scan:
    """The result of the scan."""

    sidecars: tuple[Sidecar, ...]
    skipped: tuple[
        str, ...
    ]  # YAML files that are not sidecars, relative to the repository root


def _scan_roots(repo_root: Path) -> list[tuple[str, Path, Path]]:
    """Return `(origin, folder to scan, cache dir)` for each root."""
    repo_root = Path(repo_root)
    return [
        (
            "package",
            repo_root / "skellytracker" / "core" / "detectors",
            repo_root / "skellytracker" / "core",
        ),
        ("example", spec_dir(repo_root) / "examples", spec_dir(repo_root) / "examples"),
    ]


def _is_sidecar(data: Any, path: Path) -> bool:
    return (
        isinstance(data, dict)
        and "schema_version" in data
        and data.get("model_id") == path.stem
    )


def _resolve(path: Path, cache_dir: Path, shown: str) -> dict[str, Any]:
    try:
        return sidecar_refs.resolve(path, cache_dir)
    except sidecar_refs.SidecarRefsError as exc:
        raise TraceError(
            f"{shown}: cannot resolve the sidecar:\n" + "\n".join(exc.errors)
        ) from exc
    except (
        Exception
    ) as exc:  # the resolver raises its own error types; importing them needs the package
        raise TraceError(
            f"{shown}: cannot resolve the sidecar: {type(exc).__name__}: {exc}"
        ) from exc


def _sort_key(sidecar: Sidecar) -> tuple[int, str, str]:
    return (
        0 if sidecar.source == PACKAGE_SOURCE else 1,
        sidecar.source,
        sidecar.model_id,
    )


def scan_sidecars(repo_root: Path = REPO_ROOT) -> Scan:
    """Find, resolve and normalize every sidecar of the two roots. See the module docstring."""
    repo_root = Path(repo_root)
    inventory = load_inventory(repo_root)
    examples_root = spec_dir(repo_root) / "examples"
    sidecars: list[Sidecar] = []
    skipped: list[str] = []
    for origin, folder, cache_dir in _scan_roots(repo_root):
        for path in sorted(folder.rglob("*.yaml")):
            shown = path.relative_to(repo_root).as_posix()
            try:
                raw = yaml.safe_load(path.read_text(encoding="utf-8"))
            except yaml.YAMLError as exc:
                raise TraceError(f"{shown}: not valid YAML: {exc}") from exc
            if not _is_sidecar(raw, path):
                skipped.append(shown)
                continue
            resolved = _resolve(path, cache_dir, shown)
            source = _source_of(resolved, origin, path, examples_root, inventory, shown)
            normalized = sidecar_normalize.normalize(resolved)
            sidecars.append(
                Sidecar(
                    key=f"{resolved['model_id']}@{source}",
                    model_id=str(resolved["model_id"]),
                    source=source,
                    origin=origin,
                    path=shown,
                    schema_version=str(resolved["schema_version"]),
                    resolved=resolved,
                    normalized=normalized,
                    derived=sidecar_normalize.derived_by(resolved),
                )
            )
    seen: dict[str, str] = {}
    for sidecar in sidecars:
        if sidecar.key in seen:
            raise TraceError(
                f"the key {sidecar.key} is used by {seen[sidecar.key]} and {sidecar.path}"
            )
        seen[sidecar.key] = sidecar.path
    return Scan(tuple(sorted(sidecars, key=_sort_key)), tuple(skipped))


def _source_of(
    resolved: Mapping[str, Any],
    origin: str,
    path: Path,
    examples_root: Path,
    inventory: Mapping[str, Any],
    shown: str,
) -> str:
    declared = resolved.get("source")
    if isinstance(declared, Mapping) and declared.get("name"):
        return str(declared["name"])
    if origin == "package":
        return PACKAGE_SOURCE
    entry = inventory["examples"].get(path.relative_to(examples_root).as_posix())
    if not isinstance(entry, Mapping) or not entry.get("source"):
        raise TraceError(
            f"{shown}: the sidecar has no `source.name` and inventory.yaml has no source for it"
        )
    return str(entry["source"])


def proposed_models(repo_root: Path = REPO_ROOT) -> list[dict[str, Any]]:
    """Return the `proposed` entries of the inventory, sorted by key."""
    entries = load_inventory(repo_root)["proposed"]
    return sorted((dict(e) for e in entries), key=lambda e: str(e.get("key", "")))


def applicable_models(
    sections: Iterable[Section], sidecars: Iterable[Sidecar]
) -> dict[str, list[Sidecar]]:
    """Return, for each section ID, the sidecars that the section applies to."""
    sidecars = list(sidecars)
    return {
        section.id: [
            sidecar
            for sidecar in sidecars
            if sidecar_normalize.applies(section.front, sidecar.normalized)
        ]
        for section in sections
    }



@dataclass(frozen=True)
class Section:
    """One section file of the spec."""

    id: str
    title: str
    kind: str
    path: str  # relative to the spec folder, with forward slashes
    front: dict[str, Any]
    body: str

    @property
    def implemented_by(self) -> dict[str, str]:
        return dict(self.front.get("implemented_by") or {})

    @property
    def status(self) -> dict[str, str]:
        return dict(self.front.get("status") or {})

    @property
    def tests(self) -> list[str]:
        return list(self.front.get("tests") or [])

    @property
    def vectors(self) -> str | None:
        return self.front.get("vectors")

    @property
    def external_impl(self) -> list[Any]:
        return list(self.front.get("external_impl") or [])


def parse_front_matter(text: str, where: str = "<text>") -> tuple[dict[str, Any], str]:
    """Split a section file into its parsed front matter and its body.

    The front matter is the text between the first two `---` lines. Raise `TraceError` when it is
    absent or is not a mapping.
    """
    match = _FRONT.match(text)
    if match is None:
        raise TraceError(
            f"{where}: the file has no front matter between two '---' lines"
        )
    try:
        data = yaml.safe_load(match.group(1))
    except yaml.YAMLError as exc:
        raise TraceError(f"{where}: the front matter is not valid YAML: {exc}") from exc
    if not isinstance(data, dict):
        raise TraceError(f"{where}: the front matter is not a mapping")
    return data, text[match.end() :]


@dataclass(frozen=True)
class SectionMapRow:
    """One row of the section map in `specs/model-sidecar/README.md`."""

    id: str
    file: str
    title: str


def readme_section_map(repo_root: Path = REPO_ROOT) -> list[SectionMapRow]:
    """Return the rows of the section map in README.md, in reading order."""
    readme = spec_dir(repo_root) / "README.md"
    rows: list[SectionMapRow] = []
    for line in readme.read_text(encoding="utf-8").splitlines():
        match = _MAP_ROW.match(line)
        if match and match["text"] == match["file"]:
            rows.append(SectionMapRow(match["id"], match["file"], match["title"]))
    return rows


def section_files(repo_root: Path = REPO_ROOT) -> list[Path]:
    """Return every section file, sorted by folder and name."""
    base = spec_dir(repo_root)
    return [
        path
        for folder in SECTION_FOLDERS
        for path in sorted((base / folder).glob("*.md"))
    ]


def load_sections(repo_root: Path = REPO_ROOT) -> list[Section]:
    """Load every section file. The order is the order of the section map in README.md.

    A section that the map does not list comes last, sorted by ID. Raise `TraceError` on a file
    with bad front matter or on a repeated section ID.
    """
    base = spec_dir(repo_root)
    found: dict[str, Section] = {}
    for path in section_files(repo_root):
        relative = path.relative_to(base).as_posix()
        front, body = parse_front_matter(path.read_text(encoding="utf-8"), relative)
        section_id = front.get("id")
        if not isinstance(section_id, str):
            raise TraceError(f"{relative}: front matter has no string `id`")
        if section_id in found:
            raise TraceError(
                f"{relative}: section ID {section_id} is also used by {found[section_id].path}"
            )
        found[section_id] = Section(
            id=section_id,
            title=str(front.get("title", "")),
            kind=str(front.get("kind", "")),
            path=relative,
            front=front,
            body=body,
        )
    order = [row.id for row in readme_section_map(repo_root)]
    listed = [found[i] for i in order if i in found]
    unlisted = sorted(
        (s for s in found.values() if s.id not in order), key=lambda s: s.id
    )
    return listed + unlisted



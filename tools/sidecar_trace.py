#!/usr/bin/env python3
"""Trace the sections of the sidecar spec to models, code, tests and vectors.

The section files of ``specs/model-sidecar/`` carry front matter. Its ``selectors`` say which sidecars a
section applies to. Its ``implemented_by``, ``tests`` and ``vectors`` say what implements and checks
the section. This tool joins that front matter with the sidecars that exist.

Commands::

    python tools/sidecar_trace.py matrix [--check]
    python tools/sidecar_trace.py impact GIT_RANGE
    python tools/sidecar_trace.py examples --exporters-root DIR

``matrix`` writes ``specs/model-sidecar/TRACEABILITY.md``. With ``--check`` it writes nothing and exits
with status 1 when the file is not up to date. Its Implementation status table also gives the
coverage of each section (vector cases, examples by ``kind``, ``V-`` rules with a case, the reference
module, the ``no_model`` reason of ``inventory.yaml``) and the graduation gate (``gate_items``).

``impact`` reads the files that ``git diff --raw GIT_RANGE`` lists. GIT_RANGE is anything that
``git diff`` accepts. For example, ``main..HEAD`` gives the commits of a branch, and ``HEAD`` gives
the uncommitted changes to files that git tracks. A section is reached when its own file or its
vector file changed, or when a function that it names in ``implemented_by`` changed. A function
changed when its text differs between the two sides of the diff (the tool reads both sides with
``git cat-file`` and ``ast``), or when one side lacks it. A new, deleted or unreadable Python file
counts as changed in whole. The report names the models, exporters, skellytracker functions, tests
and vectors that the reached sections reach. A section that its own file or its vector file reaches
lists all its functions. A section that only a function reaches lists the functions that changed.
The tool reads the models from the working tree. It changes no file.

``examples`` compares each reference example with the exporter's copy
(``DIR/<exporter>/<exporter_path>``, from ``specs/model-sidecar/inventory.yaml``). It resolves ``$ref``
and ``base`` on both sides with ``sidecar_refs.resolve`` and compares the parsed YAML, so comments
and ``$ref`` fragments do not count. When the exporter's copy does not resolve, the tool compares
it as written and says so. It prints to stdout only. CI does not run it: CI has no exporter
checkouts.

**Front matter.** ``implemented_by`` names one function for each step of the section, as
``path::Symbol`` or ``missing``. A ``missing`` step is in the backlog of ``TRACEABILITY.md``. A
preprocessor has an ``inverse`` step only when its algorithm has an inverse. The section has an
"Inverse" heading exactly when it has the step. Normalization and interpolation have no inverse, so
they have no ``inverse`` step and no entry in the backlog for it.

**Scan.** Two roots hold sidecars: the package (``skellytracker/core/detectors/``, with the cache
dir ``skellytracker/core``) and the examples (``specs/model-sidecar/examples/``, with that folder as the
cache dir). A YAML file is a sidecar when its top level has ``schema_version`` and a ``model_id``
equal to its file name without the extension. The tool skips every other YAML file. It resolves
each sidecar with ``sidecar_refs.resolve``, which accepts files without hashes. The key of a sidecar
is ``<model_id>@<source>``: ``source.name`` when the sidecar has it, else ``skellytracker`` for the
package root, else the ``source`` of the example in ``inventory.yaml``. Every example holds
``source.name`` now, and no inventory entry has a ``source``, so the examples of this repo do not
use the last fallback. The tool keeps it for an example without ``source``. Then the tool
normalizes the resolved sidecar with ``sidecar_normalize`` and matches the section selectors
against it.
The models that ``inventory.yaml`` lists under ``proposed`` are listed, but not matched.

The tool resolves and matches. It does not validate sidecars.
"""


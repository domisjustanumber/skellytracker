def _git(repo_root: Path, *arguments: str) -> bytes:
    """Run a read-only git command and return its standard output."""
    git = shutil.which("git")
    if git is None:
        raise TraceError("git is not on the PATH")
    result = subprocess.run(  # noqa: S603
        [git, "-C", str(repo_root), *arguments], capture_output=True, check=False
    )
    if result.returncode != 0:
        raise TraceError(
            f"git {arguments[0]} failed: {result.stderr.decode('utf-8', 'replace').strip()}"
        )
    return result.stdout


@dataclass(frozen=True)
class DiffEntry:
    """One file of a git diff. A blob ID of None means that the side has no committed blob."""

    path: str  # relative to the repository root, with forward slashes
    status: str  # A (added), M (modified), D (deleted) or T (type changed)
    old_blob: str | None
    new_blob: (
        str | None
    )  # None for a deleted file, or for a file read from the working tree


def _blob_id(text: str) -> str | None:
    return None if set(text) == {"0"} else text


def diff_entries(git_range: str, repo_root: Path = REPO_ROOT) -> list[DiffEntry]:
    """Return the files that `git diff --raw GIT_RANGE` lists, sorted by path.

    GIT_RANGE is anything that `git diff` accepts: `main..HEAD`, `A...B`, or one revision such as
    `HEAD`, which compares that revision with the working tree. `git diff` does not list a file
    that git does not track yet.
    """
    if not git_range or git_range.startswith("-"):
        raise TraceError(f"bad git range {git_range!r}")
    output = _git(
        repo_root, "diff", "--raw", "--no-abbrev", "--no-renames", "-z", git_range, "--"
    ).decode("utf-8")
    fields = output.split("\0")
    entries = []
    for header, path in zip(fields[0::2], fields[1::2], strict=False):
        parts = header.removeprefix(":").split()
        if not header.startswith(":") or len(parts) != 5:
            raise TraceError(f"unexpected line in the output of git diff: {header!r}")
        entries.append(
            DiffEntry(path, parts[4][0], _blob_id(parts[2]), _blob_id(parts[3]))
        )
    return sorted(entries, key=lambda entry: entry.path)


def changed_files(git_range: str, repo_root: Path = REPO_ROOT) -> list[str]:
    """Return the files that `git diff GIT_RANGE` lists, with forward slashes."""
    return sorted({entry.path for entry in diff_entries(git_range, repo_root)})


def _source_text(data: bytes) -> str:
    return data.decode("utf-8-sig", errors="replace")


def _changed_symbols(
    entry: DiffEntry, symbols: Iterable[str], repo_root: Path
) -> frozenset[str] | None:
    """Return the symbols whose text differs between the two sides of a diff entry.

    Return None when the whole file counts as changed: the file is new or deleted, its type
    changed, or a side is not a Python module that `ast` can read.
    """
    if entry.status != "M" or entry.old_blob is None:
        return None
    try:
        old = _source_text(_git(repo_root, "cat-file", "blob", entry.old_blob))
        if entry.new_blob is not None:
            new = _source_text(_git(repo_root, "cat-file", "blob", entry.new_blob))
        else:  # the right side of the diff is the working tree
            new = _source_text((Path(repo_root) / entry.path).read_bytes())
        return frozenset(
            symbol
            for symbol in symbols
            if symbol_text(old, symbol) != symbol_text(new, symbol)
        )
    except (OSError, SyntaxError, ValueError, TraceError):
        return None


def changed_code(
    entries: Iterable[DiffEntry],
    sections: Iterable[Section],
    repo_root: Path = REPO_ROOT,
) -> dict[str, frozenset[str] | None]:
    """Return, for each changed file that a section names, the named symbols that changed.

    `implemented_by` names `path::Symbol`. A symbol changed when its text, with its decorators,
    differs between the two sides of the diff, or when a side lacks it. The value is None when
    the whole file counts as changed (see `_changed_symbols`). The value is an empty set when
    the file changed but none of the symbols that sections name did. A file that no section
    names is not in the result.
    """
    named: dict[str, set[str]] = {}
    for section in sections:
        for reference in section.implemented_by.values():
            parts = split_reference(reference)
            if parts is not None:
                named.setdefault(parts[0], set()).add(parts[1])
    return {
        entry.path: _changed_symbols(entry, named[entry.path], repo_root)
        for entry in entries
        if entry.path in named
    }


@dataclass(frozen=True)
class AffectedSection:
    """A section that a change reaches, and everything that the section reaches."""

    section: Section
    reasons: tuple[str, ...]
    models: tuple[str, ...]
    exporters: tuple[str, ...]
    functions: tuple[str, ...]
    tests: tuple[str, ...]
    vectors: tuple[str, ...]


def _exporters_of(
    sidecars: Iterable[Sidecar], inventory: Mapping[str, Any]
) -> list[str]:
    prefix = "specs/model-sidecar/examples/"
    found = set()
    for sidecar in sidecars:
        if sidecar.origin != "example":
            continue
        entry = inventory["examples"].get(sidecar.path.removeprefix(prefix))
        if entry:
            found.add(f"{entry['exporter']}: {entry['exporter_path']}")
    return sorted(found)


def affected_sections(
    changed: Iterable[str],
    repo_root: Path = REPO_ROOT,
    code: Mapping[str, frozenset[str] | None] | None = None,
) -> list[AffectedSection]:
    """Return the sections that the changed files reach, in section-map order.

    A section is reached when its own file changed, when its vector file changed, or when a
    function that it names in `implemented_by` changed. `code` says which functions changed in
    each changed Python file (see `changed_code`). A changed file that `code` does not list, or
    lists as None, counts as changed in whole: it reaches every section that names a function in
    it.

    A section that its own file or its vector file reaches lists all its functions: they
    implement the text that changed. A section that only a function reaches lists the functions
    that changed.
    """
    changed = set(changed)
    code = code or {}
    sections = load_sections(repo_root)
    sidecars = list(scan_sidecars(repo_root).sidecars)
    applicable = applicable_models(sections, sidecars)
    inventory = load_inventory(repo_root)
    base = "/".join(SPEC_DIR_PARTS)
    result = []
    for section in sections:
        reasons = []
        if f"{base}/{section.path}" in changed:
            reasons.append(f"section file changed: {base}/{section.path}")
        if section.vectors and f"{base}/{section.vectors}" in changed:
            reasons.append(f"vector file changed: {base}/{section.vectors}")
        text_changed = bool(reasons)
        functions, changed_functions = [], []
        for reference in section.implemented_by.values():
            parts = split_reference(reference)
            if parts is None:
                continue
            functions.append(reference)
            path, symbol = parts
            if path not in changed:
                continue
            symbols = code.get(path)
            if symbols is None:
                reasons.append(f"implementing file changed: {path}")
            elif symbol in symbols:
                reasons.append(f"implementing function changed: {reference}")
            else:
                continue
            changed_functions.append(reference)
        if not reasons:
            continue
        models = applicable[section.id]
        result.append(
            AffectedSection(
                section=section,
                reasons=tuple(dict.fromkeys(reasons)),
                models=tuple(s.key for s in models),
                exporters=tuple(_exporters_of(models, inventory)),
                functions=tuple(
                    dict.fromkeys(functions if text_changed else changed_functions)
                ),
                tests=tuple(section.tests),
                vectors=(f"{base}/{section.vectors}",) if section.vectors else (),
            )
        )
    return result


def impact(
    git_range: str, repo_root: Path = REPO_ROOT
) -> tuple[list[str], list[AffectedSection]]:
    """Return the changed files of a git range and the sections that the change reaches."""
    entries = diff_entries(git_range, repo_root)
    changed = sorted({entry.path for entry in entries})
    code = changed_code(entries, load_sections(repo_root), repo_root)
    return changed, affected_sections(changed, repo_root, code)


def format_impact(
    git_range: str, changed: list[str], affected: list[AffectedSection]
) -> str:
    """Return the text that the `impact` command prints."""
    lines = [f"Range: {git_range}", f"Changed files: {len(changed)}"]
    if not affected:
        lines.append("No section is affected.")
        return "\n".join(lines) + "\n"
    lines.append(f"Affected sections: {len(affected)}")
    for item in affected:
        lines.extend(["", item.section.id])
        lines.extend(f"  reason: {reason}" for reason in item.reasons)
        for label, values in (
            ("models", item.models),
            ("exporters", item.exporters),
            ("functions", item.functions),
            ("tests", item.tests),
            ("vectors", item.vectors),
        ):
            lines.append(f"  {label}: " + (", ".join(values) if values else "none"))
    lines.extend(["", "Summary"])
    for label, getter in (
        ("sections", lambda a: (a.section.id,)),
        ("models", lambda a: a.models),
        ("exporters", lambda a: a.exporters),
        ("functions", lambda a: a.functions),
        ("tests", lambda a: a.tests),
        ("vectors", lambda a: a.vectors),
    ):
        values = sorted({value for item in affected for value in getter(item)})
        lines.append(f"  {label} ({len(values)}):")
        lines.extend(f"    {value}" for value in values)
    return "\n".join(lines) + "\n"



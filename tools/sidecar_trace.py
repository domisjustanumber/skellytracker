def split_reference(value: str) -> tuple[str, str] | None:
    """Split `path::Symbol` into its two parts. Return None for the value `missing`.

    Raise `TraceError` when the value has any other form.
    """
    if value == MISSING:
        return None
    path, separator, symbol = value.partition(_SYMBOL_SEPARATOR)
    if not separator or not path or not symbol or _SYMBOL_SEPARATOR in symbol:
        raise TraceError(f"{value!r} is neither 'missing' nor 'path::Symbol'")
    return path, symbol


def _symbol_node(
    tree: ast.Module, symbol: str
) -> ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef | None:
    """Return the node of `Class`, `Class.method` or `function` at the top level of a module."""
    parts = symbol.split(".")
    if not 1 <= len(parts) <= 2:
        return None
    functions = (ast.FunctionDef, ast.AsyncFunctionDef)
    for node in tree.body:
        if len(parts) == 1 and isinstance(node, (*functions, ast.ClassDef)):
            if node.name == parts[0]:
                return node
        elif (
            len(parts) == 2 and isinstance(node, ast.ClassDef) and node.name == parts[0]
        ):
            return next(
                (
                    member
                    for member in node.body
                    if isinstance(member, functions) and member.name == parts[1]
                ),
                None,
            )
    return None


def find_symbol(source: str, symbol: str) -> bool:
    """Return True when a module defines `Class`, `Class.method` or `function` at its top level.

    This reads the source with `ast`. It imports nothing.
    """
    return _symbol_node(ast.parse(source), symbol) is not None


_LINE_BREAK = re.compile(r"\r\n|\r|\n")


def symbol_text(source: str, symbol: str) -> str | None:
    """Return the lines of a symbol, with its decorators, or None when the module lacks it.

    The text has no trailing white space and no line-ending difference, so two revisions of a
    file give equal text for a symbol that did not change. Line numbers that other symbols move
    do not matter.
    """
    node = _symbol_node(ast.parse(source), symbol)
    if node is None:
        return None
    first = min([node.lineno, *(decorator.lineno for decorator in node.decorator_list)])
    lines = _LINE_BREAK.split(source)[first - 1 : node.end_lineno]
    return "\n".join(line.rstrip() for line in lines)



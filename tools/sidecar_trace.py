_FRONT = re.compile(r"\A---\r?\n(.*?)\r?\n---[ \t]*(?:\r?\n|\Z)", re.DOTALL)
_MAP_ROW = re.compile(
    r"^\|\s*`(?P<id>[^`]+)`\s*\|\s*\[(?P<text>[^\]]+)\]\((?P<file>[^)]+)\)\s*\|\s*(?P<title>.+?)\s*\|\s*$"
)
_SYMBOL_SEPARATOR = "::"
MISSING = "missing"


class TraceError(Exception):
    """A problem in the spec files, the sidecars or the command line."""


def spec_dir(repo_root: Path = REPO_ROOT) -> Path:
    """Return the folder of the split spec."""
    return Path(repo_root).joinpath(*SPEC_DIR_PARTS)



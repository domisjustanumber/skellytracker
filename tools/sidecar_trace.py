_SHOWN = 48


def _short_text(text: str) -> str:
    return text if len(text) <= _SHOWN else text[: _SHOWN - 3] + "..."


def _short(value: Any) -> str:
    return _short_text(repr(value))


def _is_container(value: Any) -> bool:
    return isinstance(value, (dict, list))


def _is_flat(items: list[Any]) -> bool:
    """Return True for a list of scalars, or a list of lists of scalars."""
    return not any(
        isinstance(item, dict)
        or (isinstance(item, list) and any(_is_container(sub) for sub in item))
        for item in items
    )


def _by_name(items: list[Any]) -> dict[str, Any] | None:
    """Return the mappings of a list by their `name`, or None when they cannot be told apart."""
    names = [item.get("name") if isinstance(item, dict) else None for item in items]
    if not names or not all(isinstance(name, str) for name in names):
        return None
    if len(set(names)) != len(names):
        return None
    return dict(zip(names, items, strict=True))


def _differ_by_name(
    example: list[Any], exporter: list[Any], path: str
) -> list[str] | None:
    """Compare two lists of named mappings by name when their names differ; else return None.

    This keeps one skeleton that exists on one side only from moving every later item.
    """
    ours, theirs = _by_name(example), _by_name(exporter)
    if ours is None or theirs is None or list(ours) == list(theirs):
        return None
    lines = []
    for name in sorted(ours.keys() | theirs.keys()):
        child = f"{path}[{name}]"
        if name not in theirs:
            lines.append(f"{child}: only in the example")
        elif name not in ours:
            lines.append(f"{child}: only in the exporter copy")
        else:
            lines.extend(diff_yaml(ours[name], theirs[name], child))
    if ours.keys() == theirs.keys():
        lines.append(f"{path or '<top level>'}: the same names in a different order")
    return lines


def _unmatched(items: list[str], others: list[str]) -> list[str]:
    """Return the items that `others` does not match one for one, in their order."""
    remaining = Counter(others)
    result = []
    for item in items:
        if remaining[item] > 0:
            remaining[item] -= 1
        else:
            result.append(item)
    return result


def _diff_flat_lists(example: list[Any], exporter: list[Any], where: str) -> list[str]:
    """Compare two lists of scalars, or of lists of scalars, as sets of items.

    A short pair of lists is shown as it is. For a longer pair, the line counts the items that
    only one side has and shows the first three of them. The same items in a different order
    are a difference too: the order of `tracked_points` is the order of the model output.
    """
    ours, theirs = [repr(item) for item in example], [repr(item) for item in exporter]
    if ours == theirs:  # `repr` tells apart 1, 1.0 and True
        return []
    if len(repr(example)) <= _SHOWN and len(repr(exporter)) <= _SHOWN:
        return [
            f"{where}: {repr(example)} in the example, {repr(exporter)} in the exporter copy"
        ]
    only = {
        "the example": _unmatched(ours, theirs),
        "the exporter copy": _unmatched(theirs, ours),
    }
    if not any(only.values()):
        return [f"{where}: the same {len(ours)} items in a different order"]
    parts = [
        f"{len(items)} only in {side}: "
        + ", ".join(_short_text(item) for item in items[:3])
        + (", ..." if len(items) > 3 else "")
        for side, items in only.items()
        if items
    ]
    return [f"{where}: " + "; ".join(parts)]


def diff_yaml(example: Any, exporter: Any, path: str = "") -> list[str]:
    """Return one line for each difference between two parsed YAML values.

    Each line starts with the dotted path of the key. A list item is `[i]`, or `[name]` when
    the two lists hold mappings with different `name` values. `example` is the value in the
    spec's example. `exporter` is the value in the exporter's copy. For a long list of scalars,
    or of lists of scalars, the line counts the items that only one side has.
    """
    where = path or "<top level>"
    if isinstance(example, dict) and isinstance(exporter, dict):
        lines: list[str] = []
        for key in example.keys() | exporter.keys():
            child = f"{path}.{key}" if path else str(key)
            if key not in exporter:
                lines.append(f"{child}: only in the example")
            elif key not in example:
                lines.append(f"{child}: only in the exporter copy")
            else:
                lines.extend(diff_yaml(example[key], exporter[key], child))
        return sorted(lines)
    if isinstance(example, list) and isinstance(exporter, list):
        by_name = _differ_by_name(example, exporter, path)
        if by_name is not None:
            return by_name
        if _is_flat(example) and _is_flat(exporter):
            return _diff_flat_lists(example, exporter, where)
        lines = []
        for index, (left, right) in enumerate(zip(example, exporter, strict=False)):
            lines.extend(diff_yaml(left, right, f"{path}[{index}]"))
        common = min(len(example), len(exporter))
        if len(example) > common:
            lines.append(
                f"{path}[{common}:]: extra items in the example: {len(example) - common}"
            )
        if len(exporter) > common:
            lines.append(
                f"{path}[{common}:]: extra items in the exporter copy: {len(exporter) - common}"
            )
        return lines
    # A scalar, or a list of scalars. `repr` tells apart 1, 1.0 and True.
    if repr(example) == repr(exporter):
        return []
    return [
        f"{where}: {_short(example)} in the example, {_short(exporter)} in the exporter copy"
    ]


@dataclass(frozen=True)
class ExampleReport:
    """The comparison of one example with the exporter's copy."""

    example: str  # key in inventory.yaml
    exporter_file: str
    status: str  # "same", "different" or "unavailable"
    lines: tuple[str, ...]
    notes: tuple[str, ...] = ()  # how the comparison was made; not differences


def _problem(exc: Exception) -> str:
    """Return the first line of the problems that `sidecar_refs.resolve` found, or the error."""
    if isinstance(exc, sidecar_refs.SidecarRefsError) and exc.errors:
        return exc.errors[0]
    return f"{type(exc).__name__}: {exc}"


def _resolved_or_plain(path: Path) -> tuple[Any, str | None]:
    """Resolve `$ref` and `base` of an exporter's copy; else read it as it is.

    Return the data and, when the copy did not resolve, the reason. Raise `yaml.YAMLError` when
    the copy is not YAML. The root of the copy is the parent of its nearest `detectors` folder,
    else its own folder.
    """
    try:
        return sidecar_refs.resolve(path, sidecar_refs.default_root(path)), None
    except Exception as exc:  # the resolver raises its own error types
        reason = _problem(exc)
    return yaml.safe_load(path.read_text(encoding="utf-8")), reason


def compare_examples(repo_root: Path, exporters_root: Path) -> list[ExampleReport]:
    """Compare each example of the inventory with the exporter's copy.

    Both sides are resolved first, so a fragment that the example refers to with `$ref` equals
    the same values written in the exporter's copy.
    """
    repo_root, exporters_root = Path(repo_root), Path(exporters_root)
    examples_root = spec_dir(repo_root) / "examples"
    reports = []
    for relative, entry in sorted(load_inventory(repo_root)["examples"].items()):
        theirs = exporters_root / entry["exporter"] / entry["exporter_path"]
        shown = f"{entry['exporter']}/{entry['exporter_path']}"
        if not theirs.is_file():
            reports.append(
                ExampleReport(
                    relative, shown, "unavailable", ("the exporter copy is missing",)
                )
            )
            continue
        try:
            ours_data = sidecar_refs.resolve(examples_root / relative, examples_root)
        except Exception as exc:  # the resolver raises its own error types
            reports.append(
                ExampleReport(
                    relative,
                    shown,
                    "unavailable",
                    (f"the example does not resolve: {_problem(exc)}",),
                )
            )
            continue
        try:
            theirs_data, reason = _resolved_or_plain(theirs)
        except yaml.YAMLError as exc:
            reports.append(
                ExampleReport(
                    relative, shown, "unavailable", (f"not valid YAML: {exc}",)
                )
            )
            continue
        notes = (
            (f"the exporter copy was compared as written, not resolved: {reason}",)
            if reason
            else ()
        )
        lines = diff_yaml(ours_data, theirs_data)
        reports.append(
            ExampleReport(
                relative,
                shown,
                "different" if lines else "same",
                tuple(lines),
                notes,
            )
        )
    return reports


def format_examples(reports: list[ExampleReport]) -> str:
    """Return the text that the `examples` command prints."""
    lines = []
    for report in reports:
        lines.append(f"{report.example}: {report.status}")
        lines.append(f"  exporter copy: {report.exporter_file}")
        lines.extend(f"  note: {note}" for note in report.notes)
        lines.extend(f"  {line}" for line in report.lines)
    counts = {
        s: sum(r.status == s for r in reports)
        for s in ("same", "different", "unavailable")
    }
    lines.append("")
    lines.append(
        f"{len(reports)} examples: {counts['same']} same, {counts['different']} different, "
        f"{counts['unavailable']} unavailable"
    )
    return "\n".join(lines) + "\n"


